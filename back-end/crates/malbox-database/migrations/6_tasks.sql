create table tasks (
    id              integer generated by default as identity primary key,
    target          varchar not null,
    plugins         varchar[] not null default '{}',      -- selected plugins (empty = all)
    excluded_plugins varchar[] not null default '{}',
    timeout         bigint not null default 300,          -- detonation timeout (s)
    priority        bigint not null default 1,
    machine_id      integer references machines(id) on delete set null,   -- requested machine
    platform        machine_platform,                     -- requested detonation platform
    snapshot_id     uuid references machine_snapshots(id) on delete set null,
    params          jsonb not null default '{}',          -- validated SubmissionParams
    max_depth       integer not null,
    max_artifacts   integer not null,
    max_detonations integer not null,
    max_total_bytes bigint not null,
    created_on      timestamp without time zone not null,
    started_on      timestamp without time zone,
    completed_on    timestamp without time zone,
    updated_at      timestamp without time zone,
    deadline        timestamptz not null,
    status          task_state not null default 'pending',
    sample_id       bigint references samples(id),        -- root sample
    parent_task_id  integer references tasks(id) on delete set null,
    owner           varchar,
    tags            varchar[],
    error_count     integer not null default 0,
    artifact_count  integer not null default 0,           -- analysed artifacts
    partial         boolean not null default false,
    shared_data     jsonb not null default '{}',          -- task-wide shared plugin data
    verdict_classification classification,
    verdict_score   smallint check (verdict_score is null or (verdict_score between 0 and 100)),
    verdict_artifact_id bigint
);
select trigger_updated_on('tasks');
create index idx_tasks_status on tasks(status);

-- circular dependency: machines.current_task_id references tasks
alter table machines add constraint machines_current_task_id_fkey
    foreign key (current_task_id) references tasks(id) on delete set null;

create table task_artifacts (
    id            bigint generated always as identity primary key,
    task_id       integer not null references tasks(id) on delete cascade,
    sha256        varchar not null,
    size_bytes    bigint not null,
    storage_path  text,                 -- null only when max_total_bytes refused the blob
    "analyze"     boolean not null,     -- quoted: analyze is a reserved word
    sample_id     bigint references samples(id),
    depth         integer not null,
    artifact_type varchar not null,
    mime          varchar not null,
    state         artifact_state not null,
    drop_reason   varchar,
    priority      bigint not null,
    deadline      timestamptz,
    canceled_by   varchar,
    promoted_task_id integer references tasks(id) on delete set null,
    dynamic_recursion_bypass boolean not null default false,
    analyze_requested boolean not null default false,   -- a plugin asked for analysis; admission pending or done
    created_on    timestamptz not null default now(),
    unique (task_id, sha256),
    check ("analyze" = (sample_id is not null))
);
create index idx_task_artifacts_sample on task_artifacts(sample_id);

create table artifact_edges (
    task_id            integer not null references tasks(id) on delete cascade,
    parent_artifact_id bigint not null references task_artifacts(id) on delete cascade,
    child_artifact_id  bigint not null references task_artifacts(id) on delete cascade,
    relation           artifact_relation not null,
    source_job_id      bigint,
    source_plugin      varchar,                         -- plugin that emitted it (guest plugins share one detonation job)
    name               text,                            -- capped and NUL-stripped by ingest
    created_on         timestamptz not null default now(),
    primary key (parent_artifact_id, child_artifact_id, relation)
);
create index idx_artifact_edges_child on artifact_edges(child_artifact_id);
create index idx_artifact_edges_task on artifact_edges(task_id);

create table jobs (
    id            bigint generated always as identity primary key,
    task_id       integer not null references tasks(id) on delete cascade,
    artifact_id   bigint not null references task_artifacts(id) on delete cascade,
    kind          job_kind not null,
    analyzer      varchar not null,     -- host plugin name, or detonation profile name ("submission" for implicit)
    stage         analysis_stage not null,
    priority      bigint not null,
    state         job_state not null default 'blocked',
    attempts      smallint not null default 0,
    max_attempts  smallint not null,
    reruns        smallint not null default 0,
    ignore_cache  boolean not null default false,
    error_class   job_error_class,
    error_message text,
    cache_key     varchar,
    cached_from_job_id bigint references jobs(id) on delete set null,
    drop_requested boolean not null default false,
    machine_id    integer references machines(id) on delete set null,
    snapshot_id   uuid references machine_snapshots(id) on delete set null,
    guest_plugins varchar[],
    detonation    jsonb,                -- resolved DetonationRequest, detonation jobs only
    not_before    timestamptz,
    started_on    timestamptz,
    completed_on  timestamptz,
    created_on    timestamptz not null default now(),
    unique (artifact_id, analyzer)
);
create index idx_jobs_ready on jobs (kind, priority desc, id) where state = 'ready';
create index idx_jobs_task on jobs(task_id);

create table result_cache (
    cache_key   varchar primary key,
    job_id      bigint not null references jobs(id) on delete cascade,
    empty       boolean not null,
    created_on  timestamptz not null default now(),
    expires_on  timestamptz not null
);
